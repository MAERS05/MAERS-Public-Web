/** 本地开源组件的可复现构建；固定版本、保留许可证，支持只读产物校验。 */
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const destination = path.join(root, 'plugins/ui-components');
const check = process.argv.includes('--check');
const packages = ['photoswipe', 'codemirror', '@codemirror', '@lezer', 'style-mod', 'w3c-keyname', 'crelt'];
const assets = new Map();
for (const [name, entry] of Object.entries({
    'editor.module.js': path.join(here, 'vendor/ui/editor.mjs'),
    'photoswipe.module.js': path.join(here, 'node_modules/photoswipe/dist/photoswipe.esm.js')
})) {
    const result = await build({ entryPoints: [entry], bundle: true, format: 'esm', target: 'es2020',
        minify: true, legalComments: 'inline', write: false, charset: 'utf8',
        banner: { js: '/* Generated by _studio/tooling/ui-vendor-build.mjs; do not edit. */' } });
    assets.set(name, result.outputFiles[0].text);
}
assets.set('photoswipe.css', await fs.readFile(path.join(here, 'node_modules/photoswipe/dist/photoswipe.css'), 'utf8'));
let licenses = '# 本地开源组件许可证\n\n由 ui-vendor-build.mjs 生成。\n';
for (const name of packages) {
    const base = path.join(here, 'node_modules', name);
    const names = name.startsWith('@') ? (await fs.readdir(base)).map(child => `${name}/${child}`) : [name];
    for (const packageName of names) {
        const directory = path.join(here, 'node_modules', packageName);
        const pkg = JSON.parse(await fs.readFile(path.join(directory, 'package.json'), 'utf8'));
        const license = (await fs.readdir(directory, { withFileTypes: true }))
            .find(file => file.isFile() && /^licen[cs]e(?:\.|$)/i.test(file.name))?.name;
        if (!license) throw Error(`缺少许可证：${packageName}`);
        licenses += `\n## ${packageName} ${pkg.version}\n\n${await fs.readFile(path.join(directory, license), 'utf8')}\n`;
    }
}
assets.set('LICENSES.txt', licenses);
if (!check) await fs.mkdir(destination, { recursive: true });
for (const [name, contents] of assets) {
    const target = path.join(destination, name);
    if (check) {
        const existing = await fs.readFile(target, 'utf8');
        if (existing.replaceAll('\r\n', '\n') !== contents.replaceAll('\r\n', '\n')) throw Error(`开源组件产物过期：${name}`);
    } else await fs.writeFile(target, contents);
}
process.stdout.write(check ? 'UI vendor assets match sources.\n' : 'UI vendor assets rebuilt.\n');
