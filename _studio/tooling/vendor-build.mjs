/** Vditor 补丁构建：验证原包及模块指纹，只将可审查源码注入已固定的基准。 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { parse } from 'acorn';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const vendor = path.join(root, '_studio/tooling/vendor/vditor');
const hash = text => crypto.createHash('sha256').update(text).digest('hex');
const manifest = JSON.parse(fs.readFileSync(path.join(vendor, 'patches.json'), 'utf8'));
function modules(source) {
    const result = new Map();
    function visit(node) {
        if (!node || typeof node !== 'object') return;
        if (node.type === 'Property' && typeof node.key?.value === 'number' &&
            ['ArrowFunctionExpression', 'FunctionExpression'].includes(node.value.type) && node.value.params.length === 3) result.set(node.key.value, node.value);
        for (const value of Object.values(node)) if (Array.isArray(value)) value.forEach(visit); else if (value && typeof value === 'object') visit(value);
    }
    visit(parse(source, { ecmaVersion: 'latest' }));
    return result;
}
let failed = false;
for (const [name, entry] of Object.entries(manifest)) {
    const original = fs.readFileSync(path.join(vendor, name), 'utf8');
    if (hash(original) !== entry.sha256) throw Error(`原始发布包已改变，请重新审查补丁：${name}`);
    const nodes = modules(original);
    const replacements = entry.patches.map(patch => {
        const node = nodes.get(patch.id);
        if (!node || hash(original.slice(node.start, node.end)) !== patch.originalHash) throw Error(`模块指纹不匹配：${patch.file}`);
        const code = fs.readFileSync(path.join(vendor, 'patches', patch.file), 'utf8');
        const ast = parse(code, { ecmaVersion: 'latest' });
        if (ast.body.length !== 1 || ast.body[0].expression?.type !== 'ArrowFunctionExpression') throw Error(`补丁必须是单个模块工厂：${patch.file}`);
        const value = ast.body[0].expression;
        return { ...node, source: code.slice(value.start, value.end) };
    }).sort((a, b) => b.start - a.start);
    let output = original;
    for (const item of replacements) output = output.slice(0, item.start) + item.source + output.slice(item.end);
    output = '/* Generated by _studio/tooling/vendor-build.mjs. Edit vendor/vditor/patches sources, not this file. */\n' + output;
    parse(output, { ecmaVersion: 'latest' });
    const target = path.join(root, 'plugins/vditor-assets', name);
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output.replaceAll('\r\n', '\n')) {
            console.error(`生成产物过期或被直接修改：${name}`); failed = true;
        }
    } else fs.writeFileSync(target, output);
}
if (failed) process.exit(1);
console.log(process.argv.includes('--check') ? 'Vditor generated assets match sources.' : 'Vditor assets rebuilt.');
